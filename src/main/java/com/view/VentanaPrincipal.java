    public void crearObjetoPersona(){
        
       int id = 0;
        if(!ID.getText().equals("0")){
            id = Integer.valueOf(ID.getText());
        }
       
       
       
        String nombre = txtNombre.getText();
        String apellido = txtApellido.getText();
        String correo = txtCorreo.getText();
        String sexo = "";

        if(Mujer.isSelected()){
            sexo = "M";
        }
        if(Hombre.isSelected()){
            sexo = "H";
        }
        String fecha = txtFecha.getText();

        persona = new Personal(id, nombre, apellido, correo, fecha, sexo);
    }
    
    public void consultarPersona(){
        
        try{
       
            modelo.setRowCount(0);
            for( Personal p : dao.consultar() ){
                //System.out.println(p.toString());
                
                modelo.addRow(new Object[]{p.getIdPersonal(),p.getNombre(),p.getApellido(),p.getCorreo(),p.getFecha(),p.getSexo(),p.calcularEdad()});
            
            }
            
        }catch(Exception ex){
            System.out.println("Error:" + ex.toString());
            
        }
    }
